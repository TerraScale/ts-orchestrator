package contracts

// CellTokenIsValid reports whether value is a canonical cell token shared by
// control-plane subjects, monitoring documents, and configuration.
func CellTokenIsValid(value string) bool {
	if len(value) < 1 || len(value) > 63 || value[0] == '-' || value[len(value)-1] == '-' {
		return false
	}
	for index := 0; index < len(value); index++ {
		character := value[index]
		if character >= 'a' && character <= 'z' || character >= '0' && character <= '9' || character == '-' {
			continue
		}
		return false
	}
	return true
}
