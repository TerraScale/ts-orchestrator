// Package security coordinates staged rotation of the credentials used by the
// control plane.  Provider implementations are deliberately kept behind the
// interfaces in this file: rotation tests and the orchestrator do not need to
// know how OCI Vault, SPIRE, member RPC, or Cloudflare Secrets Store work.
package security

import (
	"context"
	"errors"
	"fmt"
	"sync"
	"time"
)

const (
	// CapabilityPeriod is the mandated capability-key lifetime (D-14/D-70).
	CapabilityPeriod = 24 * time.Hour
	// DefaultExpirySafety leaves enough time to distribute and activate a
	// generation. A generation close to expiry is never activated.
	DefaultExpirySafety = 5 * time.Minute
	// CapabilityBucket is the edge capability/origin-proof bucket width. The
	// key itself lives for CapabilityPeriod; readers accept the current and
	// immediately previous bucket while a long poll crosses a boundary.
	CapabilityBucket  = 10 * time.Minute
	CapabilityOverlap = CapabilityBucket
)

// Phase is the durable rotation state machine phase.
type Phase string

const (
	PhasePrepare    Phase = "prepare"
	PhaseDistribute Phase = "distribute"
	PhaseVerify     Phase = "verify"
	PhaseActivate   Phase = "activate"
	PhaseRetire     Phase = "retire"
	PhaseActive     Phase = "active"
	PhaseFailed     Phase = "failed-closed"
)

// ErrNoState tells a StateStore that this is the first rotation. Stores may
// instead return nil state, which has the same meaning.
var ErrNoState = errors.New("rotation state does not exist")

// IdentityRequest is intentionally metadata-only. Secret material is
// generated by the issuer and is not part of a durable request.
type IdentityRequest struct {
	OperationID    string
	Generation     uint64
	NotBefore      time.Time
	ExpiresAt      time.Time
	IdempotencyKey string
}

// IdentityMaterial is returned by an issuer and exists only while one
// transition is being executed. Reference is safe to persist; the byte fields
// are private to the provider boundary and are never copied into state.
type IdentityMaterial struct {
	Reference   string
	Version     uint64
	NotBefore   time.Time
	ExpiresAt   time.Time
	WorkloadTLS []byte
	ControlTLS  []byte
	TrustBundle []byte
}

// CapabilityRequest describes a 24-hour HMAC key bucket.
type CapabilityRequest struct {
	OperationID    string
	Generation     uint64
	Bucket         int64
	NotBefore      time.Time
	ExpiresAt      time.Time
	IdempotencyKey string
}

// CapabilityMaterial is transient provider material. Key is never persisted,
// logged, audited, or included in a coordinator error.
type CapabilityMaterial struct {
	// ID is a non-secret provider key identifier. It is safe to persist and
	// include in receipts; Key is transient material and is always wiped.
	ID        string
	Reference string
	Version   uint64
	Bucket    int64
	NotBefore time.Time
	ExpiresAt time.Time
	Key       []byte
}

// CapabilityKeyState is the persisted, secret-free half of a key-ring entry.
// The corresponding bytes are fetched only for a provider call.
type CapabilityKeyState struct {
	ID        string
	Reference string
	Version   uint64
	Bucket    int64
	NotBefore time.Time
	ExpiresAt time.Time
}

// CapabilityKeyRing is the explicit current+previous contract shared by
// members and the edge. Previous is retained until its expiry (one
// ten-minute bucket overlap at the edge boundary).
type CapabilityKeyRing struct {
	Current  CapabilityKeyState
	Previous CapabilityKeyState
}

func (r CapabilityKeyRing) IDs() (current, previous string) {
	return r.Current.ID, r.Previous.ID
}

// Validate rejects ambiguous rings before publication. Empty Previous is
// valid for the first rotation; once present, IDs and references must differ.
func (r CapabilityKeyRing) Validate() error {
	if r.Current.ID == "" || r.Current.Reference == "" {
		return errors.New("security: current capability key identity is required")
	}
	if r.Previous.ID == "" && r.Previous.Reference == "" {
		return nil
	}
	if r.Previous.ID == "" || r.Previous.Reference == "" || r.Previous.ID == r.Current.ID || r.Previous.Reference == r.Current.Reference {
		return errors.New("security: capability key ring is ambiguous")
	}
	return nil
}

// IdentityIssuer is the SPIFFE issuer/Vault certificate seam. Fetch permits a
// restart to resume from a reference without persisting a certificate.
type IdentityIssuer interface {
	Issue(ctx context.Context, request IdentityRequest) (IdentityMaterial, error)
	Fetch(ctx context.Context, reference string) (IdentityMaterial, error)
	Retire(ctx context.Context, reference string, idempotencyKey string) error
}

// Issuer is the concise name used by coordinator wiring.
type Issuer = IdentityIssuer

// CapabilityVault creates and retrieves HMAC keys by opaque Vault reference.
type CapabilityVault interface {
	Generate(ctx context.Context, request CapabilityRequest) (CapabilityMaterial, error)
	Fetch(ctx context.Context, reference string) (CapabilityMaterial, error)
	Retire(ctx context.Context, reference string, idempotencyKey string) error
}

// Vault is the concise name used by coordinator wiring.
type Vault = CapabilityVault

// CredentialSet is passed to a member or edge provider in memory. Providers
// must treat it as borrowed and must not persist or log it.
type CredentialSet struct {
	Identity           IdentityMaterial
	Capability         CapabilityMaterial
	PreviousCapability CapabilityMaterial
}

// ConsumerObservation is the provider's signed/attested answer that a
// generation is installed and usable. ValidUntil is checked to prevent an
// already-expired consumer from being accepted.
type ConsumerObservation struct {
	Generation uint64
	ValidUntil time.Time
}

// MemberGateway distributes credentials to all members in a Region. Every
// mutating method receives an idempotency key so uncertain provider responses
// are safe to retry after a crash.
type MemberGateway interface {
	Members(ctx context.Context, region string) ([]string, error)
	Distribute(ctx context.Context, member string, credentials CredentialSet, idempotencyKey string) error
	Verify(ctx context.Context, member string, generation uint64) (ConsumerObservation, error)
	Activate(ctx context.Context, member string, generation uint64, idempotencyKey string) error
	Retire(ctx context.Context, member string, generation uint64, idempotencyKey string) error
	Rollback(ctx context.Context, member string, generation uint64, idempotencyKey string) error
	// Fence disables acceptance of capabilities/control traffic in a Region.
	// It is called on every failed or ambiguous multi-Region transition.
	Fence(ctx context.Context, region string, idempotencyKey string) error
}

// Member is retained as a readable seam name for callers wiring member RPC.
type Member = MemberGateway

// SecretsStore is the Cloudflare Secrets Store seam. It is global because the
// edge capability secret is shared by authorization-equivalent clients.
type SecretsStore interface {
	Distribute(ctx context.Context, credentials CredentialSet, idempotencyKey string) error
	Verify(ctx context.Context, generation uint64) (ConsumerObservation, error)
	Activate(ctx context.Context, generation uint64, idempotencyKey string) error
	Retire(ctx context.Context, generation uint64, idempotencyKey string) error
	Rollback(ctx context.Context, generation uint64, idempotencyKey string) error
	Fence(ctx context.Context, idempotencyKey string) error
}

// PublicationReceipt is the bounded acknowledgement returned by providers
// that can atomically publish a member key ring and the Snippet key ring. It
// deliberately contains identifiers and digests only, never values.
type PublicationReceipt struct {
	OperationID   string
	Generation    uint64
	ReceiptID     string
	CurrentKeyID  string
	PreviousKeyID string
	Committed     bool
}

// AtomicPublisher is an optional stronger publication seam. Implementations
// must make member and Snippet publication one provider transaction (or leave
// both sides unchanged), and must retain the receipt for idempotent retry.
type AtomicPublisher interface {
	Publish(ctx context.Context, operationID string, generation uint64, credentials CredentialSet, idempotencyKey string) (PublicationReceipt, error)
	RollbackPublication(ctx context.Context, receipt PublicationReceipt, idempotencyKey string) error
}

// CloudflareSecretsStore documents the concrete provider represented by the
// generic SecretsStore seam.
type CloudflareSecretsStore = SecretsStore

// Reloader reloads mTLS material in the local member/control process. It is
// separate from MemberGateway because a member agent and the control process
// have different restart/reload mechanisms.
type Reloader interface {
	Reload(ctx context.Context, region string, credentials CredentialSet, idempotencyKey string) error
	Verify(ctx context.Context, region string, generation uint64) (ConsumerObservation, error)
	Rollback(ctx context.Context, region string, generation uint64, idempotencyKey string) error
	Fence(ctx context.Context, region string, idempotencyKey string) error
}

// StateStore is the crash-restart boundary. Implementations must atomically
// replace state. State has no secret fields by construction.
type StateStore interface {
	Load(ctx context.Context) (PersistedState, error)
	Save(ctx context.Context, state PersistedState) error
}

// DurableState is an alternate name for the crash-restart store seam.
type DurableState = StateStore

// AuditFact is safe for an audit stream: it contains only bounded metadata and
// error codes, never provider errors or secret material.
type AuditFact struct {
	OperationID string
	Generation  uint64
	Phase       Phase
	Outcome     string
	Code        string
	At          time.Time
}

type AuditSink interface {
	Record(context.Context, AuditFact) error
}

// PersistedState is the complete restart journal for one active transition.
// References are opaque and must not be dereferenced by a StateStore.
type PersistedState struct {
	OperationID          string
	Generation           uint64
	Phase                Phase
	LastVersion          uint64
	LastAt               time.Time
	Regions              []string
	OldIdentityRef       string
	OldCapabilityRef     string
	OldCapabilityID      string
	OldVersion           uint64
	OldExpiry            time.Time
	CurrentIdentityRef   string
	CurrentCapabilityRef string
	CurrentCapabilityID  string
	PreviousCapabilityID string
	CurrentVersion       uint64
	CurrentExpiry        time.Time
	NewIdentityRef       string
	NewCapabilityRef     string
	NewCapabilityID      string
	NewVersion           uint64
	NewBucket            int64
	NewNotBefore         time.Time
	NewExpiry            time.Time
	Members              map[string][]string
	Distributed          map[string]bool
	Verified             map[string]bool
	Activated            map[string]bool
	Retired              map[string]bool
	EdgeDistributed      bool
	EdgeVerified         bool
	EdgeActivated        bool
	PublicationReceipt   PublicationReceipt
	PublicationCommitted bool
	FailureCode          string
}

// RotationResult is a redacted view returned to callers.
type RotationResult struct {
	OperationID   string
	Generation    uint64
	Phase         Phase
	Regions       []string
	OldVersion    uint64
	NewVersion    uint64
	NewBucket     int64
	NewExpiry     time.Time
	CurrentKeyID  string
	PreviousKeyID string
}

// Config supplies all external effects. All fields are required except Clock,
// Audit, and ExpirySafety. A clock is injected to make expiry tests hermetic.
type Config struct {
	Issuer  IdentityIssuer
	Vault   CapabilityVault
	Members MemberGateway
	Secrets SecretsStore
	// Publisher, when supplied, is the atomic member+Snippet publication
	// adapter. The legacy stage adapters remain available for deployments that
	// compose those operations separately.
	Publisher    AtomicPublisher
	Reloader     Reloader
	State        StateStore
	Audit        AuditSink
	Regions      []string
	Clock        func() time.Time
	ExpirySafety time.Duration
}

// Coordinator performs one serialized rotation at a time. Provider calls are
// made without exposing secret material outside the injected interfaces.
type Coordinator struct {
	issuer    IdentityIssuer
	vault     CapabilityVault
	members   MemberGateway
	secrets   SecretsStore
	publisher AtomicPublisher
	reloader  Reloader
	state     StateStore
	audit     AuditSink
	regions   []string
	clock     func() time.Time
	safety    time.Duration
	mu        sync.Mutex
}

// RotationCoordinator is the explicit name used by integrations.
type RotationCoordinator = Coordinator

func NewCoordinator(config Config) (*Coordinator, error) {
	if config.Issuer == nil || config.Vault == nil || config.Members == nil || config.Secrets == nil || config.Reloader == nil || config.State == nil {
		return nil, &RotationError{Code: "configuration_invalid"}
	}
	if len(config.Regions) == 0 {
		return nil, &RotationError{Code: "regions_missing"}
	}
	seen := make(map[string]struct{}, len(config.Regions))
	regions := make([]string, len(config.Regions))
	for i, region := range config.Regions {
		if region == "" {
			return nil, &RotationError{Code: "region_invalid"}
		}
		if _, ok := seen[region]; ok {
			return nil, &RotationError{Code: "region_duplicate"}
		}
		seen[region] = struct{}{}
		regions[i] = region
	}
	clock := config.Clock
	if clock == nil {
		clock = time.Now
	}
	safety := config.ExpirySafety
	if safety <= 0 {
		safety = DefaultExpirySafety
	}
	if safety >= CapabilityPeriod {
		return nil, &RotationError{Code: "expiry_safety_invalid"}
	}
	return &Coordinator{issuer: config.Issuer, vault: config.Vault, members: config.Members, secrets: config.Secrets, publisher: config.Publisher, reloader: config.Reloader, state: config.State, audit: config.Audit, regions: regions, clock: clock, safety: safety}, nil
}

// NewRotationCoordinator is an explicit constructor alias.
func NewRotationCoordinator(config Config) (*Coordinator, error) { return NewCoordinator(config) }

// Rotate starts or resumes an operation. An identical operation ID is
// idempotent; a different operation cannot overtake an unfinished one.
func (c *Coordinator) Rotate(ctx context.Context, operationID string) (RotationResult, error) {
	if c == nil || operationID == "" {
		return RotationResult{}, &RotationError{Code: "operation_invalid"}
	}
	if err := ctx.Err(); err != nil {
		return RotationResult{}, &RotationError{Code: "context_cancelled"}
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	state, err := c.load(ctx)
	if err != nil {
		return RotationResult{}, err
	}
	now := c.clock().UTC()
	if now.IsZero() {
		return RotationResult{}, &RotationError{Code: "clock_invalid"}
	}
	if !state.LastAt.IsZero() && now.Before(state.LastAt) {
		return RotationResult{}, &RotationError{Code: "clock_regressed"}
	}
	if state.Phase != "" && state.Phase != PhaseActive && state.Phase != PhaseFailed && state.OperationID != operationID {
		return RotationResult{}, &RotationError{Code: "operation_in_progress"}
	}
	if state.OperationID == operationID && state.Phase == PhaseActive {
		return c.result(state), nil
	}
	if state.OperationID == operationID && state.Phase == PhaseFailed {
		return RotationResult{}, &RotationError{Code: "rotation_failed_closed"}
	}
	if state.OperationID == "" || state.Phase == PhaseActive || state.Phase == PhaseFailed {
		if state.LastVersion == ^uint64(0) || state.NewVersion == ^uint64(0) || state.CurrentVersion == ^uint64(0) {
			return RotationResult{}, &RotationError{Code: "version_exhausted"}
		}
		state = c.newState(state, operationID, now)
		if err := c.save(ctx, state); err != nil {
			return RotationResult{}, err
		}
	}
	return c.resume(ctx, state, now)
}

// Resume continues the operation recorded in durable state. It is useful to
// let the reconciler retry after a process restart without inventing an ID.
func (c *Coordinator) Resume(ctx context.Context) (RotationResult, error) {
	if c == nil {
		return RotationResult{}, &RotationError{Code: "coordinator_invalid"}
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	state, err := c.load(ctx)
	if err != nil {
		return RotationResult{}, err
	}
	if state.OperationID == "" {
		return RotationResult{}, &RotationError{Code: "nothing_to_resume"}
	}
	if state.Phase == PhaseFailed {
		return RotationResult{}, &RotationError{Code: "rotation_failed_closed"}
	}
	now := c.clock().UTC()
	if !state.LastAt.IsZero() && now.Before(state.LastAt) {
		return RotationResult{}, &RotationError{Code: "clock_regressed"}
	}
	return c.resume(ctx, state, now)
}

// RetireExpired removes the previous bucket once every consumer has reported
// the new generation and its expiry has passed. Retiring early would violate
// D-14's one-bucket overlap.
func (c *Coordinator) RetireExpired(ctx context.Context) (RotationResult, error) {
	if c == nil {
		return RotationResult{}, &RotationError{Code: "coordinator_invalid"}
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	state, err := c.load(ctx)
	if err != nil {
		return RotationResult{}, err
	}
	if state.Phase != PhaseActive || state.OldVersion == 0 {
		return c.result(state), nil
	}
	now := c.clock().UTC()
	if now.Before(state.OldExpiry) {
		return c.result(state), nil
	}
	if err := c.retireAt(ctx, &state); err != nil {
		return RotationResult{}, c.failClosed(ctx, state, "retire_failed")
	}
	return c.result(state), nil
}

func (c *Coordinator) resume(ctx context.Context, state PersistedState, now time.Time) (RotationResult, error) {
	if state.Phase == PhasePrepare {
		if err := c.prepare(ctx, &state, now); err != nil {
			return RotationResult{}, c.failClosed(ctx, state, "preparation_failed")
		}
	}
	identity, capability, err := c.material(ctx, state)
	if err != nil {
		return RotationResult{}, c.failClosed(ctx, state, "material_unavailable")
	}
	defer wipe(identity.WorkloadTLS)
	defer wipe(identity.ControlTLS)
	defer wipe(identity.TrustBundle)
	defer wipe(capability.Key)
	previousCapability, err := c.previousCapability(ctx, state, now)
	if err != nil {
		// Legacy stage adapters predate the current+previous key-ring
		// contract and may not retain material across a process restart. The
		// atomic publisher is the production contract and must fail closed.
		if c.publisher != nil {
			return RotationResult{}, c.failClosed(ctx, state, "previous_material_unavailable")
		}
		previousCapability = CapabilityMaterial{}
	}
	defer wipe(previousCapability.Key)
	if now.After(state.NewExpiry) || state.NewExpiry.Sub(now) <= c.safety {
		return RotationResult{}, c.failClosed(ctx, state, "generation_expired")
	}
	credentials := CredentialSet{Identity: identity, Capability: capability, PreviousCapability: previousCapability}
	if state.Phase == PhaseDistribute {
		if err := c.distribute(ctx, &state, credentials); err != nil {
			return RotationResult{}, c.transitionFailure(ctx, state, "distribution_failed")
		}
		state.Phase = PhaseVerify
		if err := c.save(ctx, state); err != nil {
			return RotationResult{}, c.transitionFailure(ctx, state, "state_save_failed")
		}
	}
	if state.Phase == PhaseVerify {
		if err := c.verify(ctx, &state, now); err != nil {
			return RotationResult{}, c.transitionFailure(ctx, state, "verification_failed")
		}
		state.Phase = PhaseActivate
		if err := c.save(ctx, state); err != nil {
			return RotationResult{}, c.transitionFailure(ctx, state, "state_save_failed")
		}
	}
	if state.Phase == PhaseActivate {
		if err := c.activate(ctx, &state, credentials); err != nil {
			return RotationResult{}, c.transitionFailure(ctx, state, "activation_failed")
		}
		state.Phase = PhaseActive
		state.CurrentIdentityRef, state.CurrentCapabilityRef = state.NewIdentityRef, state.NewCapabilityRef
		state.CurrentCapabilityID = state.NewCapabilityID
		state.PreviousCapabilityID = state.OldCapabilityID
		state.CurrentVersion, state.CurrentExpiry = state.NewVersion, state.NewExpiry
		state.LastAt = now
		if err := c.save(ctx, state); err != nil {
			return RotationResult{}, c.transitionFailure(ctx, state, "state_save_failed")
		}
	}
	if state.Phase == PhaseRetire {
		if state.OldVersion == 0 || now.Before(state.OldExpiry) {
			return RotationResult{}, c.failClosed(ctx, state, "retire_not_safe")
		}
		if err := c.retireOld(ctx, state); err != nil {
			return RotationResult{}, c.failClosed(ctx, state, "retire_failed")
		}
		state.OldIdentityRef, state.OldCapabilityRef, state.OldCapabilityID, state.OldVersion = "", "", "", 0
		state.PreviousCapabilityID = ""
		state.OldExpiry = time.Time{}
		state.Phase = PhaseActive
		if err := c.save(ctx, state); err != nil {
			return RotationResult{}, c.failClosed(ctx, state, "state_save_failed")
		}
	} else if state.Phase == PhaseActive && state.OldVersion != 0 && !now.Before(state.OldExpiry) {
		if err := c.retireAt(ctx, &state); err != nil {
			return RotationResult{}, c.failClosed(ctx, state, "retire_failed")
		}
	}
	if c.audit != nil {
		_ = c.audit.Record(ctx, AuditFact{OperationID: state.OperationID, Generation: state.NewVersion, Phase: state.Phase, Outcome: "success", Code: "rotation_complete", At: now})
	}
	return c.result(state), nil
}

func (c *Coordinator) retireAt(ctx context.Context, state *PersistedState) error {
	state.Phase = PhaseRetire
	if err := c.save(ctx, *state); err != nil {
		return err
	}
	if err := c.retireOld(ctx, *state); err != nil {
		return err
	}
	state.OldIdentityRef, state.OldCapabilityRef, state.OldCapabilityID, state.OldVersion = "", "", "", 0
	state.PreviousCapabilityID = ""
	state.OldExpiry = time.Time{}
	state.Phase = PhaseActive
	return c.save(ctx, *state)
}

func (c *Coordinator) prepare(ctx context.Context, state *PersistedState, now time.Time) error {
	identity, err := c.issuer.Issue(ctx, IdentityRequest{OperationID: state.OperationID, Generation: state.NewVersion, NotBefore: state.NewNotBefore, ExpiresAt: state.NewExpiry, IdempotencyKey: key(*state, "issue-identity", "", "")})
	if err != nil {
		return err
	}
	if identity.Reference == "" || identity.Version != state.NewVersion || identity.ExpiresAt.Before(state.NewExpiry) {
		wipe(identity.WorkloadTLS)
		wipe(identity.ControlTLS)
		wipe(identity.TrustBundle)
		return errors.New("provider returned invalid identity")
	}
	// Persist the opaque identity reference before creating the HMAC key. A
	// restart can therefore repeat the provider operation by idempotency key,
	// and an orphaned certificate can be retired if key generation fails.
	state.NewIdentityRef = identity.Reference
	if err := c.save(ctx, *state); err != nil {
		_ = c.issuer.Retire(ctx, identity.Reference, key(*state, "identity-retire-orphan", "", ""))
		wipe(identity.WorkloadTLS)
		wipe(identity.ControlTLS)
		wipe(identity.TrustBundle)
		return err
	}
	capability, err := c.vault.Generate(ctx, CapabilityRequest{OperationID: state.OperationID, Generation: state.NewVersion, Bucket: state.NewBucket, NotBefore: state.NewNotBefore, ExpiresAt: state.NewExpiry, IdempotencyKey: key(*state, "generate-capability", "", "")})
	if err != nil {
		_ = c.issuer.Retire(ctx, identity.Reference, key(*state, "identity-retire-orphan", "", ""))
		wipe(identity.WorkloadTLS)
		wipe(identity.ControlTLS)
		wipe(identity.TrustBundle)
		return err
	}
	defer wipe(identity.WorkloadTLS)
	defer wipe(identity.ControlTLS)
	defer wipe(identity.TrustBundle)
	defer wipe(capability.Key)
	if capability.Reference == "" || capability.Version != state.NewVersion || capability.Bucket != state.NewBucket || capability.ExpiresAt.Before(state.NewExpiry) {
		_ = c.issuer.Retire(ctx, identity.Reference, key(*state, "identity-retire-orphan", "", ""))
		if capability.Reference != "" {
			_ = c.vault.Retire(ctx, capability.Reference, key(*state, "capability-retire-orphan", "", ""))
		}
		return errors.New("provider returned invalid material")
	}
	if capability.ID == "" {
		// Providers should return an ID. Keep a deterministic fallback for old
		// adapters while ensuring the durable journal still carries no secret.
		capability.ID = fmt.Sprintf("generation-%d", state.NewVersion)
	}
	state.NewIdentityRef, state.NewCapabilityRef, state.NewCapabilityID = identity.Reference, capability.Reference, capability.ID
	state.Phase = PhaseDistribute
	return c.save(ctx, *state)
}

func (c *Coordinator) distribute(ctx context.Context, state *PersistedState, credentials CredentialSet) error {
	if c.publisher != nil {
		// Resolve and journal the complete member set before handing it to the
		// atomic adapter. A receipt can then be replayed or rolled back after a
		// process restart without rediscovering a different membership set.
		for _, region := range state.Regions {
			if len(state.Members[region]) != 0 {
				continue
			}
			members, err := c.members.Members(ctx, region)
			if err != nil {
				return err
			}
			if len(members) == 0 {
				return errors.New("no members")
			}
			state.Members[region] = append([]string(nil), members...)
			if err := c.save(ctx, *state); err != nil {
				return err
			}
		}
		if !state.PublicationCommitted {
			receipt, err := c.publisher.Publish(ctx, state.OperationID, state.NewVersion, credentials, key(*state, "publish", "", ""))
			if err != nil {
				return err
			}
			if receipt.Generation != state.NewVersion || receipt.OperationID != state.OperationID || receipt.ReceiptID == "" || !receipt.Committed {
				return errors.New("invalid publication receipt")
			}
			state.PublicationReceipt = receipt
			state.PublicationCommitted = true
			state.EdgeDistributed = true
			for _, region := range state.Regions {
				state.Distributed[region] = true
			}
			if err := c.save(ctx, *state); err != nil {
				return err
			}
		}
		for _, region := range state.Regions {
			if err := c.reloader.Reload(ctx, region, credentials, key(*state, "reload", region, "")); err != nil {
				return err
			}
		}
		return nil
	}
	for _, region := range state.Regions {
		if state.Distributed[region] {
			continue
		}
		members, err := c.members.Members(ctx, region)
		if err != nil {
			return err
		}
		if len(members) == 0 {
			return errors.New("no members")
		}
		state.Members[region] = append([]string(nil), members...)
		if err := c.save(ctx, *state); err != nil {
			return err
		}
		for i, member := range members {
			if err := c.members.Distribute(ctx, member, credentials, key(*state, "distribute", region, fmt.Sprint(i))); err != nil {
				return err
			}
		}
		if err := c.reloader.Reload(ctx, region, credentials, key(*state, "reload", region, "")); err != nil {
			return err
		}
		state.Members[region] = append([]string(nil), members...)
		state.Distributed[region] = true
		if err := c.save(ctx, *state); err != nil {
			return err
		}
	}
	if !state.EdgeDistributed {
		if c.publisher == nil {
			if err := c.secrets.Distribute(ctx, credentials, key(*state, "edge-distribute", "", "")); err != nil {
				return err
			}
			state.EdgeDistributed = true
			if err := c.save(ctx, *state); err != nil {
				return err
			}
		}
	}
	return nil
}

func (c *Coordinator) transitionFailure(ctx context.Context, state PersistedState, code string) error {
	// Rollback is best effort: any uncertainty is followed by fencing, and the
	// durable failed-closed state makes the next attempt an explicit operation.
	_ = c.rollback(ctx, state)
	return c.failClosed(ctx, state, code)
}

func (c *Coordinator) rollback(ctx context.Context, state PersistedState) error {
	var first error
	if c.publisher != nil && state.PublicationReceipt.ReceiptID != "" {
		if err := c.publisher.RollbackPublication(ctx, state.PublicationReceipt, key(state, "publish-rollback", "", "")); err != nil {
			// Continue fencing/legacy cleanup below so a partial provider
			// rollback cannot leave an accepting edge or member.
			first = err
		}
	}
	for _, region := range state.Regions {
		for i, member := range state.Members[region] {
			if err := c.members.Rollback(ctx, member, state.NewVersion, key(state, "rollback", region, fmt.Sprint(i))); err != nil && first == nil {
				first = err
			}
		}
		if err := c.reloader.Rollback(ctx, region, state.NewVersion, key(state, "reload-rollback", region, "")); err != nil && first == nil {
			first = err
		}
	}
	if c.publisher == nil {
		if err := c.secrets.Rollback(ctx, state.NewVersion, key(state, "edge-rollback", "", "")); err != nil && first == nil {
			first = err
		}
	}
	return first
}

func (c *Coordinator) verify(ctx context.Context, state *PersistedState, now time.Time) error {
	for _, region := range state.Regions {
		if state.Verified[region] {
			continue
		}
		members := state.Members[region]
		if len(members) == 0 {
			return errors.New("members not distributed")
		}
		for _, member := range members {
			observation, err := c.members.Verify(ctx, member, state.NewVersion)
			if err != nil || !usable(observation, state.NewVersion, state.NewExpiry, now) {
				return errors.New("member verification failed")
			}
		}
		if observation, err := c.reloader.Verify(ctx, region, state.NewVersion); err != nil || !usable(observation, state.NewVersion, state.NewExpiry, now) {
			return errors.New("reloader verification failed")
		}
		state.Verified[region] = true
		if err := c.save(ctx, *state); err != nil {
			return err
		}
	}
	if !state.EdgeVerified {
		observation, err := c.secrets.Verify(ctx, state.NewVersion)
		if err != nil || !usable(observation, state.NewVersion, state.NewExpiry, now) {
			return errors.New("edge verification failed")
		}
		state.EdgeVerified = true
		if err := c.save(ctx, *state); err != nil {
			return err
		}
	}
	return nil
}

func (c *Coordinator) activate(ctx context.Context, state *PersistedState, credentials CredentialSet) error {
	for _, region := range state.Regions {
		if state.Activated[region] {
			continue
		}
		for i, member := range state.Members[region] {
			if err := c.members.Activate(ctx, member, state.NewVersion, key(*state, "activate", region, fmt.Sprint(i))); err != nil {
				return err
			}
		}
		if err := c.reloader.Reload(ctx, region, credentials, key(*state, "reload-activate", region, "")); err != nil {
			return err
		}
		state.Activated[region] = true
		if err := c.save(ctx, *state); err != nil {
			return err
		}
	}
	if !state.EdgeActivated {
		if err := c.secrets.Activate(ctx, state.NewVersion, key(*state, "edge-activate", "", "")); err != nil {
			return err
		}
		state.EdgeActivated = true
		if err := c.save(ctx, *state); err != nil {
			return err
		}
	}
	return nil
}

func (c *Coordinator) retireOld(ctx context.Context, state PersistedState) error {
	for _, region := range state.Regions {
		for i, member := range state.Members[region] {
			if err := c.members.Retire(ctx, member, state.OldVersion, key(state, "retire", region, fmt.Sprint(i))); err != nil {
				return err
			}
		}
	}
	if err := c.issuer.Retire(ctx, state.OldIdentityRef, key(state, "identity-retire", "", "")); err != nil {
		return err
	}
	if err := c.vault.Retire(ctx, state.OldCapabilityRef, key(state, "capability-retire", "", "")); err != nil {
		return err
	}
	if err := c.secrets.Retire(ctx, state.OldVersion, key(state, "edge-retire", "", "")); err != nil {
		return err
	}
	return nil
}

func (c *Coordinator) material(ctx context.Context, state PersistedState) (IdentityMaterial, CapabilityMaterial, error) {
	identity, err := c.issuer.Fetch(ctx, state.NewIdentityRef)
	if err != nil {
		return IdentityMaterial{}, CapabilityMaterial{}, err
	}
	capability, err := c.vault.Fetch(ctx, state.NewCapabilityRef)
	if err != nil {
		wipe(identity.WorkloadTLS)
		wipe(identity.ControlTLS)
		wipe(identity.TrustBundle)
		return IdentityMaterial{}, CapabilityMaterial{}, err
	}
	if identity.Version != state.NewVersion || identity.ExpiresAt.Before(state.NewExpiry) || capability.Version != state.NewVersion || capability.Bucket != state.NewBucket || capability.ExpiresAt.Before(state.NewExpiry) {
		wipe(identity.WorkloadTLS)
		wipe(identity.ControlTLS)
		wipe(identity.TrustBundle)
		wipe(capability.Key)
		return IdentityMaterial{}, CapabilityMaterial{}, errors.New("material version mismatch")
	}
	if state.NewCapabilityID != "" && capability.ID != "" && capability.ID != state.NewCapabilityID {
		wipe(identity.WorkloadTLS)
		wipe(identity.ControlTLS)
		wipe(identity.TrustBundle)
		wipe(capability.Key)
		return IdentityMaterial{}, CapabilityMaterial{}, errors.New("material key identity mismatch")
	}
	return identity, capability, nil
}

func (c *Coordinator) previousCapability(ctx context.Context, state PersistedState, now time.Time) (CapabilityMaterial, error) {
	if state.OldCapabilityRef == "" || state.OldVersion == 0 {
		return CapabilityMaterial{}, nil
	}
	material, err := c.vault.Fetch(ctx, state.OldCapabilityRef)
	if err != nil {
		return CapabilityMaterial{}, err
	}
	// The previous key may be inside its overlap window, but accepting an
	// already expired provider result would make a partial rotation appear
	// healthy. No bytes or provider details escape this boundary.
	if material.Version != state.OldVersion || material.ExpiresAt.Before(state.OldExpiry) || !now.Before(material.ExpiresAt) {
		wipe(material.Key)
		return CapabilityMaterial{}, errors.New("previous capability version mismatch")
	}
	if state.OldCapabilityID != "" && material.ID != "" && material.ID != state.OldCapabilityID {
		wipe(material.Key)
		return CapabilityMaterial{}, errors.New("previous capability key identity mismatch")
	}
	return material, nil
}

func (c *Coordinator) failClosed(ctx context.Context, state PersistedState, code string) error {
	state.Phase = PhaseFailed
	state.FailureCode = code
	for _, region := range state.Regions {
		_ = c.members.Fence(ctx, region, key(state, "fence", region, ""))
		_ = c.reloader.Fence(ctx, region, key(state, "reload-fence", region, ""))
	}
	_ = c.secrets.Fence(ctx, key(state, "edge-fence", "", ""))
	_ = c.save(ctx, state)
	if c.audit != nil {
		_ = c.audit.Record(ctx, AuditFact{OperationID: state.OperationID, Generation: state.NewVersion, Phase: PhaseFailed, Outcome: "failed", Code: code, At: c.clock().UTC()})
	}
	return &RotationError{Code: code}
}

func (c *Coordinator) load(ctx context.Context) (PersistedState, error) {
	state, err := c.state.Load(ctx)
	if errors.Is(err, ErrNoState) {
		return emptyState(c.regions), nil
	}
	if err != nil {
		return PersistedState{}, &RotationError{Code: "state_load_failed"}
	}
	if state.Members == nil {
		state.Members = map[string][]string{}
	}
	if state.Distributed == nil {
		state.Distributed = map[string]bool{}
	}
	if state.Verified == nil {
		state.Verified = map[string]bool{}
	}
	if state.Activated == nil {
		state.Activated = map[string]bool{}
	}
	if state.Retired == nil {
		state.Retired = map[string]bool{}
	}
	return state, nil
}

func (c *Coordinator) save(ctx context.Context, state PersistedState) error {
	if err := c.state.Save(ctx, state); err != nil {
		return &RotationError{Code: "state_save_failed"}
	}
	return nil
}

func (c *Coordinator) newState(previous PersistedState, operationID string, now time.Time) PersistedState {
	base := previous.LastVersion
	if previous.NewVersion > base {
		base = previous.NewVersion
	}
	if previous.CurrentVersion > base {
		base = previous.CurrentVersion
	}
	version := base + 1
	currentIdentity, currentCapability, currentCapabilityID := previous.CurrentIdentityRef, previous.CurrentCapabilityRef, previous.CurrentCapabilityID
	currentVersion, currentExpiry := previous.CurrentVersion, previous.CurrentExpiry
	if currentVersion == 0 && previous.Phase == PhaseActive {
		// Compatibility with state written before Current* was introduced.
		currentIdentity, currentCapability, currentCapabilityID, currentVersion, currentExpiry = previous.NewIdentityRef, previous.NewCapabilityRef, previous.NewCapabilityID, previous.NewVersion, previous.NewExpiry
	}
	identityExpiry := now.Add(CapabilityPeriod)
	// A previous key is retained only for the edge overlap window. The
	// provider material itself may have a longer not-after, but keeping it in
	// the active ring longer than one bucket would violate D-70 and needlessly
	// widen the replay window.
	oldExpiry := currentExpiry
	if !oldExpiry.IsZero() {
		overlapExpiry := now.Add(CapabilityOverlap)
		if overlapExpiry.Before(oldExpiry) {
			oldExpiry = overlapExpiry
		}
	}
	bucket := now.Unix() / int64(CapabilityPeriod/time.Second)
	return PersistedState{OperationID: operationID, Generation: version, Phase: PhasePrepare, LastVersion: version, LastAt: now, Regions: append([]string(nil), c.regions...), OldIdentityRef: currentIdentity, OldCapabilityRef: currentCapability, OldCapabilityID: currentCapabilityID, OldVersion: currentVersion, OldExpiry: oldExpiry, CurrentIdentityRef: currentIdentity, CurrentCapabilityRef: currentCapability, CurrentCapabilityID: currentCapabilityID, PreviousCapabilityID: previous.PreviousCapabilityID, CurrentVersion: currentVersion, CurrentExpiry: currentExpiry, NewVersion: version, NewBucket: bucket, NewNotBefore: now, NewExpiry: identityExpiry, Members: map[string][]string{}, Distributed: map[string]bool{}, Verified: map[string]bool{}, Activated: map[string]bool{}, Retired: map[string]bool{}}
}

func (c *Coordinator) result(state PersistedState) RotationResult {
	version, expiry := state.NewVersion, state.NewExpiry
	if state.CurrentVersion != 0 {
		version, expiry = state.CurrentVersion, state.CurrentExpiry
	}
	return RotationResult{OperationID: state.OperationID, Generation: state.Generation, Phase: state.Phase, Regions: append([]string(nil), state.Regions...), OldVersion: state.OldVersion, NewVersion: version, NewBucket: state.NewBucket, NewExpiry: expiry, CurrentKeyID: state.CurrentCapabilityID, PreviousKeyID: state.PreviousCapabilityID}
}

func emptyState(regions []string) PersistedState {
	return PersistedState{Regions: append([]string(nil), regions...), Members: map[string][]string{}, Distributed: map[string]bool{}, Verified: map[string]bool{}, Activated: map[string]bool{}, Retired: map[string]bool{}}
}
func usable(observation ConsumerObservation, version uint64, expiry, now time.Time) bool {
	return observation.Generation == version && !observation.ValidUntil.Before(expiry) && now.Before(observation.ValidUntil)
}
func key(state PersistedState, stage, region, item string) string {
	return "rotation/" + state.OperationID + "/" + fmt.Sprint(state.NewVersion) + "/" + stage + "/" + region + "/" + item
}
func wipe(value []byte) {
	for i := range value {
		value[i] = 0
	}
}

// RotationError intentionally omits wrapped provider errors. Provider errors
// can contain response bodies, certificates, keys, or cloud request details.
type RotationError struct{ Code string }

func (e *RotationError) Error() string {
	if e == nil {
		return ""
	}
	return "security rotation failed: " + e.Code
}
