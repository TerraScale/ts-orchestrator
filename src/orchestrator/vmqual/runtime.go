package vmqual

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"io"
	"os"
	"path/filepath"

	"terrascale.tech/orchestrator/src/orchestrator/sandboxvm"
	"terrascale.tech/orchestrator/src/orchestrator/vmdisk"
)

type sandboxVM struct {
	provider *sandboxvm.Provider
	disks    *vmdisk.Store
	guest    Guest
	id       string
}

func (v *sandboxVM) StartReady(ctx context.Context) error {
	return v.provider.StartAndWaitReady(ctx, v.id)
}
func (v *sandboxVM) Stop(ctx context.Context) error { return v.provider.Stop(ctx, v.id) }
func (v *sandboxVM) Delete(ctx context.Context) error {
	return errors.Join(v.provider.Delete(ctx, v.id), v.disks.Delete(ctx, v.id))
}
func (v *sandboxVM) Inspect(ctx context.Context) (VMObservation, error) {
	info, err := v.provider.Inspect(ctx, v.id)
	if err != nil {
		return VMObservation{}, err
	}
	return VMObservation{ID: v.id, Region: v.guest.Region, Running: info.State == sandboxvm.StateRunning, Ready: info.Ready, MemoryMiB: info.Config.MemoryMiB}, nil
}

type firecrackerFactory struct {
	provider *sandboxvm.Provider
	image    ImageResult
	disks    *vmdisk.Store
	config   Config
}

// NewFirecrackerFactory is the production command-side factory. The tagged
// runtime binds it to the official SDK; unit tests should inject VMFactory
// instead of calling this constructor.
func NewFirecrackerFactory(config Config, image ImageResult) (VMFactory, error) {
	if err := config.Validate(); err != nil {
		return nil, err
	}
	if image.Installed.Dir == "" {
		return nil, errors.New("vmqual: installed image is required")
	}
	provider, err := newSandboxVMProvider(config)
	if err != nil {
		return nil, err
	}
	disks, err := vmdisk.NewStore(filepath.Join(config.Root, "drives"))
	if err != nil {
		return nil, err
	}
	return &firecrackerFactory{provider: provider, image: image, disks: disks, config: config}, nil
}
func (f *firecrackerFactory) Create(ctx context.Context, guest Guest) (VM, error) {
	drive, err := f.disks.Preallocate(ctx, guest.ID, 64<<20)
	if err != nil {
		return nil, err
	}
	vmConfig := sandboxvm.Config{ID: guest.ID, Region: string(guest.Region), VCPU: guest.VCPU, MemoryMiB: guest.MemoryMiB, KernelImage: f.image.Installed.Kernel, RootDrive: f.image.Installed.RootFS, DataDrive: drive.Path, StateRoot: f.config.StateRoot, SocketPath: filepath.Join(f.config.StateRoot, guest.ID, "firecracker.sock"), FirecrackerBinary: f.config.FirecrackerPath, JailerBinary: f.config.JailerPath, ExpectedVersion: f.config.ExpectedVersion, ExpectedKernelSHA256: f.config.ExpectedKernelSHA256, ExpectedRootDriveSHA256: f.config.ExpectedRootFSSHA256, ExpectedDataDriveSHA256: "", ExpectedFirecrackerSHA256: f.config.ExpectedFirecrackerSHA256, ExpectedJailerSHA256: f.config.ExpectedJailerSHA256, ReadinessTimeout: f.config.ReadinessTimeout, StopTimeout: f.config.StopTimeout}
	// Data disks are generated by the pinned vmdisk provider, so their digest
	// is not a static artifact pin. The VM provider still requires a digest;
	// obtain it from the immutable file before creating the VMM.
	if digest, digestErr := fileSHA256(drive.Path); digestErr != nil {
		return nil, digestErr
	} else {
		vmConfig.ExpectedDataDriveSHA256 = digest
	}
	if _, err := f.provider.Create(ctx, vmConfig); err != nil {
		_ = f.disks.Delete(context.Background(), guest.ID)
		return nil, err
	}
	return &sandboxVM{provider: f.provider, disks: f.disks, guest: guest, id: guest.ID}, nil
}

func fileSHA256(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}
