// Guest declares one launch host. Control is co-hosted on the first member of
// each Region and is intentionally part of the topology, not a seventh VM.
type Guest struct {
	ID        string
	Region    vmnet.RegionCode
	VCPU      int64
	MemoryMiB int64
	Control   bool
	Service   bool
}

func LaunchGuests(memoryMiB int64) []Guest {
	if memoryMiB == 0 {
		memoryMiB = DefaultMemoryMiB
	}
	guests := make([]Guest, 0, 6)
	for _, region := range []vmnet.RegionCode{vmnet.GRU, vmnet.SFO, vmnet.FRA} {
		for i := 1; i <= 2; i++ {
			guests = append(guests, Guest{ID: fmt.Sprintf("%s-member-%d", stringsLower(string(region)), i), Region: region, VCPU: 1, MemoryMiB: memoryMiB, Control: i == 1, Service: true})
		}
	}
	return guests
}

// VM is the narrow lifecycle contract needed by the coordinator. Production
// orchestrator packages are not reachable through this test-only interface.
type VM interface {
	StartReady(context.Context) error
	Stop(context.Context) error
	Delete(context.Context) error
	Inspect(context.Context) (VMObservation, error)
}
type VMObservation struct {
	ID         string
	Region     vmnet.RegionCode
	Running    bool
	Ready      bool
	MemoryMiB  int64
	RSSBytes   uint64
	IdleCPU    float64
	CPUSampled bool
	Process    VMProcessIdentity
	Resources  VMResourceIdentity
}

// VMProcessIdentity binds a journaled process to the exact Linux process
// incarnation observed by the VM adapter. PID alone is unsafe because the
// kernel may reuse it before a crashed controller replays its journal.
type VMProcessIdentity struct {
	PID            int    `json:"pid"`
	StartTimeTicks uint64 `json:"startTimeTicks"`
	Executable     string `json:"executable"`
}

// VMResourceIdentity is the exact host-side cleanup plan for one guest. A
// factory that creates host resources supplies it before Create is called and
// confirms the same values through VMObservation after startup.
type VMResourceIdentity struct {
	RunID                string            `json:"runId"`
	StateDir             string            `json:"stateDir,omitempty"`
	SandboxOwnershipPath string            `json:"sandboxOwnershipPath,omitempty"`
	RunMarkerPath        string            `json:"runMarkerPath,omitempty"`
	RuntimePath          string            `json:"runtimePath,omitempty"`
	JailRoot             string            `json:"jailRoot,omitempty"`
	SocketPath           string            `json:"socketPath,omitempty"`
	LogPath              string            `json:"logPath,omitempty"`
	MetricsPath          string            `json:"metricsPath,omitempty"`
	CgroupRoot           string            `json:"cgroupRoot,omitempty"`
	CgroupPath           string            `json:"cgroupPath,omitempty"`
	JailerCgroupPath     string            `json:"jailerCgroupPath,omitempty"`
	FirecrackerPath      string            `json:"firecrackerPath,omitempty"`
	DriveDir             string            `json:"driveDir,omitempty"`
	DrivePath            string            `json:"drivePath,omitempty"`
	DriveMetadataPath    string            `json:"driveMetadataPath,omitempty"`
	DriveOwnershipPath   string            `json:"driveOwnershipPath,omitempty"`
	SeedDir              string            `json:"seedDir,omitempty"`
	Process              VMProcessIdentity `json:"process,omitempty"`
}

type VMFactory interface {
	Create(context.Context, Guest) (VM, error)
}

// VMResourcePlanner is an optional, mutation-free extension used to make a
// crash-recovery journal durable before VMFactory.Create can create a drive or
// jail. Factories without host resources need not implement it.
type VMResourcePlanner interface {
	PlanResources(context.Context, Guest) (VMResourceIdentity, error)
}

type diskStoreIdentityPlanner interface {
	PlanDiskStore(context.Context) (vmdisk.StoreIdentity, error)
}

type diskStoreFinalizer interface {
	FinalizeDiskStore(context.Context, vmdisk.StoreIdentity) error
}
type NetworkController interface {
	Apply(context.Context) error
	Cleanup(context.Context) error
}

type StackConfig struct {
	// RequireResourceEvidence makes the suite reject missing kernel samples.
	// The real VM command enables it explicitly; controller fixtures may omit it.
	RequireResourceEvidence bool
	Guests                  []Guest
	VMFactory               VMFactory
	Network                 NetworkController
	JournalPath             string
	StateRoot               string
	// ResourceRoot owns qualification artifacts outside StateRoot. When it is
	// empty and StateRoot ends in "state", NewStack uses StateRoot's parent.
	ResourceRoot string
	// RunID is normally generated by NewStack. Supplying it is useful only to
	// resume or deterministically exercise one qualification run.
	RunID        string
	MaxRSSBytes  int64
	MaxIdleCPU   float64
	MaxDiskBytes int64
}

// VMResourceReport contains only measurements observed from one participating
// VM. Create and ready durations are recorded at their actual lifecycle
// boundaries; resource peaks are updated at every suite evidence gate.
type VMResourceReport struct {
	ID                  string           `json:"id"`
	Region              vmnet.RegionCode `json:"region"`
	ConfiguredMemoryMiB int64            `json:"configuredMemoryMiB"`
	CreateDuration      time.Duration    `json:"createDuration"`
	BootStartedAt       time.Time        `json:"bootStartedAt"`
	ReadyAt             time.Time        `json:"readyAt"`
	BootToReadyDuration time.Duration    `json:"bootToReadyDuration"`
	IdleRSSBytes        uint64           `json:"idleRSSBytes"`
	PeakRSSBytes        uint64           `json:"peakRSSBytes"`
	IdleCPU             float64          `json:"idleCPU"`
	PeakIdleCPU         float64          `json:"peakIdleCPU"`
	HostDiskBytes       uint64           `json:"hostDiskBytes"`
}

type StackResourceReport struct {
	ConfiguredMemoryMiB int64              `json:"configuredMemoryMiB"`
	IdleRSSBytes        uint64             `json:"idleRSSBytes"`
	PeakRSSBytes        uint64             `json:"peakRSSBytes"`
	IdleCPU             float64            `json:"idleCPU"`
	PeakIdleCPU         float64            `json:"peakIdleCPU"`
	HostDiskBytes       uint64             `json:"hostDiskBytes"`
	PeakHostDiskBytes   uint64             `json:"peakHostDiskBytes"`
	VMs                 []VMResourceReport `json:"vms"`
}

type Stack struct {
	diagnosticMu               sync.Mutex
	failureDiagnostics         []FailureDiagnostic
	failureDiagnosticError     error
	failureDiagnosticsCaptured bool
	cleanupProbe               bool
	config                     StackConfig
	lifecycleMu                sync.Mutex
	mu                         sync.Mutex
	guests                     []Guest
	vms                        map[string]VM
	networkApplied             bool
	started                    bool
	runID                      string
	resource                   map[string]VMResourceReport
	peakRSSBytes               uint64
	peakIdleCPU                float64
	peakDiskBytes              uint64

	journalMu   sync.Mutex
	journal     *Journal
	journalLock *os.File
}

func NewStack(config StackConfig) (*Stack, error) {
	return newStack(config, false)
}

func newStack(config StackConfig, cleanupProbe bool) (*Stack, error) {
	if config.VMFactory == nil {
		return nil, errors.New("vmqual: VM factory is required")
	}
	if config.Network == nil {
		return nil, errors.New("vmqual: network controller is required")
	}
	if len(config.Guests) == 0 {
		config.Guests = LaunchGuests(DefaultMemoryMiB)
	}
	if config.MaxRSSBytes == 0 {
		config.MaxRSSBytes = MaxIdleRSSBytes
	}
	if config.MaxIdleCPU == 0 {
		config.MaxIdleCPU = MaxIdleCPU
	}
	if config.MaxDiskBytes == 0 {
		config.MaxDiskBytes = 8 << 30
	}
	if config.MaxDiskBytes < 0 {
		return nil, errors.New("vmqual: host disk budget must be positive")
	}
	if config.JournalPath != "" {
		if !filepath.IsAbs(config.JournalPath) || config.StateRoot == "" || !filepath.IsAbs(config.StateRoot) {
			return nil, errors.New("vmqual: journal and state root must be absolute")
		}
		if config.ResourceRoot == "" && filepath.Base(filepath.Clean(config.StateRoot)) == "state" {
			config.ResourceRoot = filepath.Dir(filepath.Clean(config.StateRoot))
		}
		if config.ResourceRoot != "" && !filepath.IsAbs(config.ResourceRoot) {
			return nil, errors.New("vmqual: resource root must be absolute")
		}
	}
	runID := config.RunID
	if runID == "" {
		var err error
		runID, err = NewRunID()
		if err != nil {
			return nil, err
		}
	}
	if !validRunID(runID) {
		return nil, errors.New("vmqual: run ID must be an RFC 4122 UUID")
	}
	config.RunID = runID
	if !cleanupProbe && len(config.Guests) != 6 {
		return nil, fmt.Errorf("vmqual: stack requires six guests, got %d", len(config.Guests))
	}
	seen := map[string]bool{}
	regions := map[vmnet.RegionCode]int{}
	controls := map[vmnet.RegionCode]int{}
	for _, guest := range config.Guests {
		if guest.ID == "" || seen[guest.ID] {
			return nil, fmt.Errorf("vmqual: duplicate or empty guest %q", guest.ID)
		}
		seen[guest.ID] = true
		if guest.VCPU != 1 || guest.MemoryMiB < 256 || guest.MemoryMiB > MaxGuestMemoryMiB {
			return nil, fmt.Errorf("vmqual: guest %s must use one vCPU and 256-512 MiB", guest.ID)
		}
		if !guest.Service {
			return nil, fmt.Errorf("vmqual: stack guest %s must host the TerraBase service", guest.ID)
		}
		if guest.Control {
			controls[guest.Region]++
		}
		regions[guest.Region]++
	}
	for _, region := range []vmnet.RegionCode{vmnet.GRU, vmnet.SFO, vmnet.FRA} {
		if cleanupProbe {
			break
		}
		if regions[region] != 2 {
			return nil, fmt.Errorf("vmqual: Region %s must have exactly two members", region)
		}
		if controls[region] != 1 {
			return nil, fmt.Errorf("vmqual: Region %s must have one co-hosted control replica", region)
		}
	}
	return &Stack{cleanupProbe: cleanupProbe, config: config, guests: append([]Guest(nil), config.Guests...), vms: map[string]VM{}, runID: runID, resource: make(map[string]VMResourceReport)}, nil
}

func (s *Stack) Start(ctx context.Context) error {
	if s == nil {
		return errors.New("vmqual: nil stack")
	}
	s.lifecycleMu.Lock()
	defer s.lifecycleMu.Unlock()
	if err := s.startBootstrap(ctx); err != nil {
		return err
	}
	return s.startRegions(ctx, vmnet.SFO, vmnet.FRA)
}

// StartBootstrap initializes the owned host network and starts exactly the two
// GRU members. RunSuite uses this boundary to prove the temporary R1 before it
// admits either candidate Region.
func (s *Stack) StartBootstrap(ctx context.Context) error {
	if s == nil {
		return errors.New("vmqual: nil stack")
	}
	s.lifecycleMu.Lock()
	defer s.lifecycleMu.Unlock()
	return s.startBootstrap(ctx)
}

func (s *Stack) startBootstrap(ctx context.Context) error {
	if ctx == nil {
		return errors.New("vmqual: nil context")
	}
	if err := s.initializeRun(ctx); err != nil {
		return err
	}
	if err := s.startSelectedGuests(ctx, map[vmnet.RegionCode]bool{vmnet.GRU: true}); err != nil {
		return err
	}
	if err := s.EnforceBudget(context.WithValue(ctx, qualificationRunIDKey{}, s.runID)); err != nil {
		return errors.Join(err, s.cleanupAfterFailure())
	}
	return nil
}

// StartRegions starts both members of each requested candidate Region. GRU
// must already be ready, and only SFO/FRA are valid launch candidates.
func (s *Stack) StartRegions(ctx context.Context, regions ...vmnet.RegionCode) error {
	if s == nil {
		return errors.New("vmqual: nil stack")
	}
	s.lifecycleMu.Lock()
	defer s.lifecycleMu.Unlock()
	return s.startRegions(ctx, regions...)
}

func (s *Stack) startRegions(ctx context.Context, regions ...vmnet.RegionCode) error {
	if ctx == nil {
		return errors.New("vmqual: nil context")
	}
	if len(regions) == 0 {
		return errors.New("vmqual: at least one candidate Region is required")
	}
	s.mu.Lock()
	gruReady := 0
	for _, guest := range s.guests {
		if guest.Region == vmnet.GRU && s.vms[guest.ID] != nil {
			gruReady++
		}
	}
	s.mu.Unlock()
	if gruReady != 2 {
		return errors.New("vmqual: both GRU bootstrap members must be ready before candidate Regions")
	}
	selected := make(map[vmnet.RegionCode]bool, len(regions))
	for _, region := range regions {
		if region != vmnet.SFO && region != vmnet.FRA {
			return fmt.Errorf("vmqual: Region %s is not a launch candidate", region)
		}
		if selected[region] {
			return fmt.Errorf("vmqual: duplicate candidate Region %s", region)
		}
		selected[region] = true
	}
	if err := s.initializeRun(ctx); err != nil {
		return err
	}
	if err := s.startSelectedGuests(ctx, selected); err != nil {
		return err
	}
	runCtx := context.WithValue(ctx, qualificationRunIDKey{}, s.runID)
	if err := s.EnforceBudget(runCtx); err != nil {
		return errors.Join(err, s.cleanupAfterFailure())
	}
	s.mu.Lock()
	s.started = len(s.vms) == len(s.guests)
	s.mu.Unlock()
	return nil
}

func (s *Stack) initializeRun(ctx context.Context) error {
	if ctx == nil {
		return errors.New("vmqual: nil context")
	}
	s.mu.Lock()
	applied := s.networkApplied
	s.mu.Unlock()
	if applied {
		return nil
	}
	runCtx := context.WithValue(ctx, qualificationRunIDKey{}, s.runID)
	if s.config.JournalPath != "" {
		networkJournal := vmnet.Journal{}
		if journaled, ok := s.config.Network.(interface{ Journal() vmnet.Journal }); ok {
			networkJournal = journaled.Journal()
		}
		if err := s.writeJournal(runCtx, s.config.JournalPath, networkJournal); err != nil {
			return fmt.Errorf("vmqual: write cleanup journal: %w", err)
		}
		if err := s.updateJournal(func(journal *Journal) error {
			journal.Phase = journalPhaseActive
			journal.NetworkPhase = networkPhaseApplying
			return nil
		}); err != nil {
			return fmt.Errorf("vmqual: journal network apply: %w", err)
		}
	}
	if err := s.config.Network.Apply(runCtx); err != nil {
		cleanupErr := s.cleanupAfterFailure()
		return errors.Join(fmt.Errorf("vmqual: apply network: %w", err), cleanupErr)
	}
	if err := s.updateJournal(func(journal *Journal) error {
		journal.NetworkPhase = networkPhaseApplied
		return nil
	}); err != nil {
		cleanupErr := s.cleanupAfterFailure()
		return errors.Join(fmt.Errorf("vmqual: journal applied network: %w", err), cleanupErr)
	}
	s.mu.Lock()
	s.networkApplied = true
	s.mu.Unlock()
	return nil
}

func (s *Stack) startSelectedGuests(ctx context.Context, selected map[vmnet.RegionCode]bool) error {
	runCtx := context.WithValue(ctx, qualificationRunIDKey{}, s.runID)
	cleanup := func() error { return s.cleanupAfterFailure() }
	for _, guest := range s.guests {
		if !selected[guest.Region] {
			continue
		}
		s.mu.Lock()
		alreadyStarted := s.vms[guest.ID] != nil
		s.mu.Unlock()
		if alreadyStarted {
			continue
		}
		if err := runCtx.Err(); err != nil {
			return errors.Join(err, cleanup())
		}
		if err := s.setVMPhase(guest.ID, vmPhaseCreating); err != nil {
			return errors.Join(fmt.Errorf("journal create %s: %w", guest.ID, err), cleanup())
		}
		createStarted := time.Now()
		vm, err := s.config.VMFactory.Create(runCtx, guest)
		createDuration := time.Since(createStarted)
		if err != nil {
			return errors.Join(fmt.Errorf("create %s: %w", guest.ID, err), cleanup())
		}
		if vm == nil {
			return errors.Join(fmt.Errorf("create %s: VM factory returned nil", guest.ID), cleanup())
		}
		s.mu.Lock()
		s.vms[guest.ID] = vm
		s.mu.Unlock()
		if err := s.bindVMToRun(guest); err != nil {
			return errors.Join(fmt.Errorf("bind %s to qualification run: %w", guest.ID, err), cleanup())
		}
		if err := s.setVMPhase(guest.ID, vmPhaseCreated); err != nil {
			return errors.Join(fmt.Errorf("journal created %s: %w", guest.ID, err), cleanup())
		}
		if err := s.setVMPhase(guest.ID, vmPhaseStarting); err != nil {
			return errors.Join(fmt.Errorf("journal start %s: %w", guest.ID, err), cleanup())
		}
		readyStarted := time.Now().UTC()
		if err := vm.StartReady(runCtx); err != nil {
			return errors.Join(fmt.Errorf("start %s: %w", guest.ID, err), cleanup())
		}
		readyAt := time.Now().UTC()
		readyDuration := readyAt.Sub(readyStarted)
		s.mu.Lock()
		measurement := s.resource[guest.ID]
		measurement.ID, measurement.Region, measurement.ConfiguredMemoryMiB = guest.ID, guest.Region, guest.MemoryMiB
		measurement.CreateDuration, measurement.BootStartedAt, measurement.ReadyAt, measurement.BootToReadyDuration = createDuration, readyStarted, readyAt, readyDuration
		s.resource[guest.ID] = measurement
		s.mu.Unlock()
		if observation, inspectErr := vm.Inspect(runCtx); inspectErr != nil {
			return errors.Join(fmt.Errorf("inspect started %s: %w", guest.ID, inspectErr), cleanup())
		} else if recordErr := s.recordVMObservation(guest, observation); recordErr != nil {
			return errors.Join(fmt.Errorf("journal process %s: %w", guest.ID, recordErr), cleanup())
		}
	}
	return nil
}

func (s *Stack) cleanupAfterFailure() error {
	diagnosticErr := s.preserveFailureDiagnostics()
	return errors.Join(diagnosticErr, s.cleanup(context.WithValue(context.Background(), qualificationRunIDKey{}, s.runID)))
}

func (s *Stack) EnforceBudget(ctx context.Context) error {
	s.mu.Lock()
	guests := append([]Guest(nil), s.guests...)
	vms := make(map[string]VM, len(s.vms))
	for id, vm := range s.vms {
		vms[id] = vm
	}
	s.mu.Unlock()
	var rss uint64
	var cpu float64
	var configuredMiB int64
	var diskBytes uint64
	active := 0
	for _, guest := range guests {
		vm := vms[guest.ID]
		if vm == nil {
			continue
		}
		active++
		observation, err := vm.Inspect(ctx)
		if err != nil {
			return fmt.Errorf("inspect %s: %w", guest.ID, err)
		}
		if !observation.Running || !observation.Ready {
			return fmt.Errorf("vmqual: %s is not ready", guest.ID)
		}
		if err := s.recordVMObservation(guest, observation); err != nil {
			return fmt.Errorf("vmqual: journal process %s: %w", guest.ID, err)
		}
		if observation.ID != "" && observation.ID != guest.ID {
			return fmt.Errorf("vmqual: %s readiness identity mismatch: %s", guest.ID, observation.ID)
		}
		if observation.Region != "" && observation.Region != guest.Region {
			return fmt.Errorf("vmqual: %s readiness Region mismatch: %s", guest.ID, observation.Region)
		}
		if observation.MemoryMiB != 0 && observation.MemoryMiB != guest.MemoryMiB {
			return fmt.Errorf("vmqual: %s readiness memory mismatch: %d MiB", guest.ID, observation.MemoryMiB)
		}
		if !ZeroProcessIdentity(observation.Process) && !observation.CPUSampled {
			return fmt.Errorf("vmqual: %s has no measured idle CPU sample", guest.ID)
		}
		var hostDiskBytes uint64
		if observer, ok := vm.(interface {
			HostDiskUsageBytes(context.Context) (uint64, error)
		}); ok {
			hostDiskBytes, err = observer.HostDiskUsageBytes(ctx)
			if err != nil {
				return fmt.Errorf("vmqual: measure %s host disk use: %w", guest.ID, err)
			}
		} else if !ZeroProcessIdentity(observation.Process) {
			return fmt.Errorf("vmqual: %s cannot report allocated host disk bytes", guest.ID)
		}
		if ^uint64(0)-diskBytes < hostDiskBytes {
			return errors.New("vmqual: aggregate allocated host disk bytes overflowed")
		}
		diskBytes += hostDiskBytes
		rss += observation.RSSBytes
		cpu += observation.IdleCPU
		configuredMiB += guest.MemoryMiB
		s.recordResourceSample(guest, observation, hostDiskBytes)
	}
	if active == 0 {
		return errors.New("vmqual: no guests are running")
	}
	if configuredMiB*1024*1024 > s.config.MaxRSSBytes {
		return fmt.Errorf("vmqual: configured memory budget exceeded: %d MiB", configuredMiB)
	}
	if rss > uint64(s.config.MaxRSSBytes) {
		return fmt.Errorf("vmqual: idle RSS budget exceeded: %d > %d", rss, s.config.MaxRSSBytes)
	}
	if cpu > s.config.MaxIdleCPU {
		return fmt.Errorf("vmqual: idle CPU budget exceeded: %.3f > %.3f", cpu, s.config.MaxIdleCPU)
	}
	if diskBytes > uint64(s.config.MaxDiskBytes) {
		return fmt.Errorf("vmqual: allocated host disk budget exceeded: %d > %d", diskBytes, s.config.MaxDiskBytes)
	}
	s.mu.Lock()
	if rss > s.peakRSSBytes {
		s.peakRSSBytes = rss
	}
	if cpu > s.peakIdleCPU {
		s.peakIdleCPU = cpu
	}
	if diskBytes > s.peakDiskBytes {
		s.peakDiskBytes = diskBytes
	}
	s.mu.Unlock()
	return nil
}

func (s *Stack) recordResourceSample(guest Guest, observation VMObservation, hostDiskBytes uint64) {
	s.mu.Lock()
	defer s.mu.Unlock()
	measurement := s.resource[guest.ID]
	measurement.ID, measurement.Region, measurement.ConfiguredMemoryMiB = guest.ID, guest.Region, guest.MemoryMiB
	measurement.IdleRSSBytes, measurement.IdleCPU, measurement.HostDiskBytes = observation.RSSBytes, observation.IdleCPU, hostDiskBytes
	if observation.RSSBytes > measurement.PeakRSSBytes {
		measurement.PeakRSSBytes = observation.RSSBytes
	}
	if observation.IdleCPU > measurement.PeakIdleCPU {
		measurement.PeakIdleCPU = observation.IdleCPU
	}
	s.resource[guest.ID] = measurement
}

// ResourceReport returns a stable copy suitable for the final qualification
// report even after the stack's VM handles have been deleted.
func (s *Stack) ResourceReport() StackResourceReport {
	if s == nil {
		return StackResourceReport{}
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	report := StackResourceReport{PeakRSSBytes: s.peakRSSBytes, PeakIdleCPU: s.peakIdleCPU, PeakHostDiskBytes: s.peakDiskBytes}
	report.VMs = make([]VMResourceReport, 0, len(s.resource))
	for _, measurement := range s.resource {
		report.VMs = append(report.VMs, measurement)
		report.ConfiguredMemoryMiB += measurement.ConfiguredMemoryMiB
		report.IdleRSSBytes += measurement.IdleRSSBytes
		report.IdleCPU += measurement.IdleCPU
		report.HostDiskBytes += measurement.HostDiskBytes
	}
	sort.Slice(report.VMs, func(i, j int) bool { return report.VMs[i].ID < report.VMs[j].ID })
	return report
}

func (s *Stack) cleanupVMs(ctx context.Context, ids []string) error {
	var errs []error
	for i := len(ids) - 1; i >= 0; i-- {
		s.mu.Lock()
		vm := s.vms[ids[i]]
		s.mu.Unlock()
		if vm == nil {
			continue
		}
		if err := s.setVMPhase(ids[i], vmPhaseCleaning); err != nil {
			errs = append(errs, fmt.Errorf("journal cleaning %s: %w", ids[i], err))
			continue
		}
		stopErr := vm.Stop(ctx)
		deleteErr := vm.Delete(ctx)
		if err := errors.Join(stopErr, deleteErr); err != nil {
			errs = append(errs, fmt.Errorf("cleanup %s: %w", ids[i], err))
			continue
		}
		if err := s.cleanupJournalVM(ctx, ids[i]); err != nil {
			errs = append(errs, fmt.Errorf("cleanup journal resources %s: %w", ids[i], err))
			continue
		}
		s.mu.Lock()
		delete(s.vms, ids[i])
		s.mu.Unlock()
	}
	return errors.Join(errs...)
}
func (s *Stack) Cleanup(ctx context.Context) error {
	if s == nil {
		return nil
	}
	if ctx == nil {
		ctx = context.Background()
	}
	s.lifecycleMu.Lock()
	defer s.lifecycleMu.Unlock()
	return s.cleanup(context.WithoutCancel(ctx))
}

func (s *Stack) cleanup(cleanCtx context.Context) error {
	s.mu.Lock()
	ids := make([]string, 0, len(s.vms))
	for id := range s.vms {
		ids = append(ids, id)
	}
	s.started = false
	s.mu.Unlock()
	sort.Strings(ids)
	vmErr := s.cleanupVMs(cleanCtx, ids)
	journalVMErr := s.cleanupJournalVMsWithoutHandles()
	resourceErr := errors.Join(vmErr, journalVMErr)
	var diskStoreErr error
	if resourceErr == nil {
		diskStoreErr = s.cleanupJournalDiskStore(cleanCtx)
	}
	var factoryErr error
	if resourceErr == nil && diskStoreErr == nil {
		if verifier, ok := s.config.VMFactory.(interface {
			VerifyNoOwnedResources(context.Context) error
		}); ok {
			factoryErr = verifier.VerifyNoOwnedResources(cleanCtx)
		}
	}
	journalStartErr := s.updateJournal(func(journal *Journal) error {
		journal.NetworkPhase = networkPhaseCleaning
		journal.Phase = journalPhaseCleaning
		return nil
	})
	netErr := s.config.Network.Cleanup(cleanCtx)
	var networkVerifyErr error
	if verifier, ok := s.config.Network.(interface {
		VerifyNoOwnedResources(context.Context) error
	}); ok {
		networkVerifyErr = verifier.VerifyNoOwnedResources(cleanCtx)
	}
	var journalFinishErr error
	if netErr == nil && networkVerifyErr == nil {
		journalFinishErr = s.updateJournal(func(journal *Journal) error {
			journal.NetworkPhase = networkPhaseCleaned
			journal.NetworkCleaned = true
			if resourceErr == nil && diskStoreErr == nil && factoryErr == nil && journalStartErr == nil {
				journal.Phase = journalPhaseComplete
			}
			return nil
		})
		s.mu.Lock()
		s.networkApplied = false
		s.mu.Unlock()
	}
	if err := errors.Join(resourceErr, diskStoreErr, factoryErr, journalStartErr, netErr, networkVerifyErr, journalFinishErr); err != nil {
		return err
	}
	return s.completeJournal()
}

func (s *Stack) Guests() []Guest {
	if s == nil {
		return nil
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]Guest(nil), s.guests...)
}

