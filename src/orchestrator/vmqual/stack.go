func (s *Stack) WriteJournal(path string, network vmnet.Journal) error {
	return s.writeJournal(context.Background(), path, network)
}

func (s *Stack) writeJournal(ctx context.Context, path string, network vmnet.Journal) error {
	if s == nil || path == "" || !filepath.IsAbs(path) {
		return errors.New("vmqual: journal path must be absolute")
	}
	if s.config.StateRoot == "" || !filepath.IsAbs(s.config.StateRoot) {
		return errors.New("vmqual: journal state root must be absolute")
	}
	s.journalMu.Lock()
	defer s.journalMu.Unlock()
	if s.journal != nil {
		if s.journal.RunID != s.runID || filepath.Clean(path) != filepath.Clean(s.config.JournalPath) {
			return errors.New("vmqual: a different cleanup journal is already active")
		}
		return nil
	}
	lock, err := acquireJournalLock(path)
	if err != nil {
		return err
	}
	s.journalLock = lock
	releaseOnError := true
	defer func() {
		if releaseOnError {
			s.releaseJournalLock()
		}
	}()

	now := time.Now().UTC()
	runMarkerPath := filepath.Join(s.config.StateRoot, ".vmqual-runs", s.runID+".json")
	resourceRoot := ""
	if s.config.ResourceRoot != "" {
		resourceRoot = filepath.Clean(s.config.ResourceRoot)
	}
	j := Journal{Version: cleanupJournalVersion, Marker: OwnershipMarker, RunID: s.runID, Revision: 1, CreatedAt: now, UpdatedAt: now, StateRoot: filepath.Clean(s.config.StateRoot), ResourceRoot: resourceRoot, RunMarkerPath: runMarkerPath, Phase: journalPhasePlanned, Network: network, NetworkPhase: networkPhasePlanned}
	if planner, ok := s.config.VMFactory.(diskStoreIdentityPlanner); ok {
		identity, err := planner.PlanDiskStore(ctx)
		if err != nil {
			return fmt.Errorf("plan disk store: %w", err)
		}
		j.DiskStore = &JournalDiskStore{Root: identity.Root, RunID: identity.RunID, JailerUID: identity.Ownership.UID, JailerGID: identity.Ownership.GID, Tombstone: identity.Tombstone}
	}
	planner, hasPlanner := s.config.VMFactory.(VMResourcePlanner)
	for _, guest := range s.guests {
		resources := VMResourceIdentity{RunID: s.runID}
		if hasPlanner {
			resources, err = planner.PlanResources(ctx, guest)
			if err != nil {
				return fmt.Errorf("plan resources for %s: %w", guest.ID, err)
			}
			if resources.RunID == "" {
				resources.RunID = s.runID
			}
			if resources.RunID != s.runID {
				return fmt.Errorf("vmqual: resource plan for %s has run ID %q", guest.ID, resources.RunID)
			}
		}
		if resources.StateDir != "" && resources.RunMarkerPath == "" {
			resources.RunMarkerPath = filepath.Join(resources.StateDir, RunMarkerName)
		}
		claimPath := filepath.Join(s.config.StateRoot, ".vmqual-runs", s.runID+".claims", guest.ID+".json")
		vm := journalVMFromResources(s.runID, guest, claimPath, resources)
		j.VMs = append(j.VMs, vm)
	}
	if err := validateJournal(j); err != nil {
		return err
	}
	marker := runOwnership{Version: runMarkerVersion, Marker: runOwnershipMarker, RunID: s.runID, JournalPath: filepath.Clean(path), StateRoot: j.StateRoot, CreatedAt: now}
	loaded, err := initializeJournalFiles(path, j, marker)
	if err != nil {
		return err
	}
	copy := loaded
	s.journal = &copy
	releaseOnError = false
	return nil
}

func (s *Stack) bindVMToRun(guest Guest) error {
	if s.config.JournalPath == "" {
		return nil
	}
	resource, err := s.journalVM(guest.ID)
	if err != nil {
		return err
	}
	if resource.StateDir == "" {
		return nil
	}
	if err := validateSandboxOwnership(resource, s.journalCreatedAt()); err != nil {
		return err
	}
	diskIdentity, err := s.diskStoreIdentity()
	if err != nil {
		return err
	}
	if err := validateDriveOwnership(resource, s.journalCreatedAt(), diskIdentity); err != nil {
		return err
	}
	marker := vmRunOwnership{Version: runMarkerVersion, Marker: runOwnershipMarker, RunID: s.runID, ID: guest.ID, Region: string(guest.Region), StateDir: resource.StateDir, CreatedAt: time.Now().UTC()}
	return ensureExclusiveJSON(resource.RunMarkerPath, marker)
}

func (s *Stack) recordVMObservation(guest Guest, observation VMObservation) error {
	process := observation.Process
	if !ZeroProcessIdentity(observation.Resources.Process) {
		if !ZeroProcessIdentity(process) && process != observation.Resources.Process {
			return errors.New("VM observation has conflicting process identities")
		}
		process = observation.Resources.Process
	}
	if !ZeroProcessIdentity(process) {
		if err := validateProcessIdentity(process); err != nil {
			return err
		}
	}
	if s.config.JournalPath == "" {
		return nil
	}
	expected, err := s.journalVM(guest.ID)
	if err != nil {
		return err
	}
	if expected.StateDir != "" {
		if !sameResourcePaths(expected, observation.Resources, s.runID) {
			return fmt.Errorf("VM %q observation does not match its cleanup plan", guest.ID)
		}
		if ZeroProcessIdentity(process) {
			return fmt.Errorf("VM %q has no durable process identity", guest.ID)
		}
	}
	return s.updateJournal(func(journal *Journal) error {
		for index := range journal.VMs {
			if journal.VMs[index].ID != guest.ID {
				continue
			}
			if !ZeroProcessIdentity(process) {
				identity := process
				journal.VMs[index].Process = &identity
			}
			journal.VMs[index].Phase = vmPhaseRunning
			return nil
		}
		return fmt.Errorf("VM %q is absent from cleanup journal", guest.ID)
	})
}

func (s *Stack) setVMPhase(id, phase string) error {
	return s.updateJournal(func(journal *Journal) error {
		for index := range journal.VMs {
			if journal.VMs[index].ID == id {
				journal.VMs[index].Phase = phase
				journal.VMs[index].Cleaned = phase == vmPhaseCleaned
				return nil
			}
		}
		return fmt.Errorf("VM %q is absent from cleanup journal", id)
	})
}

func (s *Stack) updateJournal(update func(*Journal) error) error {
	if s == nil || s.config.JournalPath == "" {
		return nil
	}
	s.journalMu.Lock()
	defer s.journalMu.Unlock()
	if s.journal == nil {
		return nil
	}
	next := cloneJournal(*s.journal)
	if err := update(&next); err != nil {
		return err
	}
	next.Revision++
	next.UpdatedAt = time.Now().UTC()
	if err := replaceJournal(s.config.JournalPath, next); err != nil {
		return err
	}
	*s.journal = next
	return nil
}

func (s *Stack) completeJournal() error {
	if s == nil || s.config.JournalPath == "" {
		return nil
	}
	s.journalMu.Lock()
	defer s.journalMu.Unlock()
	if err := removeJournalFile(s.config.JournalPath, s.runID); err != nil {
		return err
	}
	markerErr := removeRunMarker(s.config.StateRoot, s.runID, s.config.JournalPath)
	s.journal = nil
	s.releaseJournalLock()
	return markerErr
}

func (s *Stack) releaseJournalLock() {
	if s.journalLock != nil {
		releaseJournalLock(s.journalLock)
		s.journalLock = nil
	}
}

func (s *Stack) journalVM(id string) (JournalVM, error) {
	s.journalMu.Lock()
	defer s.journalMu.Unlock()
	if s.journal == nil {
		return JournalVM{}, errors.New("cleanup journal is not initialized")
	}
	for _, resource := range s.journal.VMs {
		if resource.ID == id {
			return resource, nil
		}
	}
	return JournalVM{}, fmt.Errorf("VM %q is absent from cleanup journal", id)
}

func (s *Stack) journalCreatedAt() time.Time {
	s.journalMu.Lock()
	defer s.journalMu.Unlock()
	if s.journal == nil {
		return time.Time{}
	}
	return s.journal.CreatedAt
}

