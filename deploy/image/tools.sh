#!/usr/bin/env bash
# Run COMMAND with the pinned image tools on PATH: qemu, libguestfs with its
# appliance, guestfs-tools, host systemd (offline systemctl/sysusers) and
# gnupg, all from the nixpkgs revision pinned in deploy/image/tools.lock.
#
# usage: tools.sh COMMAND [ARG...]
#        tools.sh --lock        rewrite tools.lock from the pinned nixpkgs
#
# tools.lock pins each tool's store path. They are realised straight from the
# binary caches without evaluating nixpkgs; when a cache lacks them, they are
# built from the pinned nixpkgs, whose outputs must equal the lock.
# TS_IMAGE_TOOL_CACHE names an extra Nix binary cache (CI: file:///cache/nix
# on the runner's shared volume) that receives the closure after a build, so
# only the first run on a runner builds libguestfs.
set -euo pipefail

(($#)) || { sed -n '2,15s/^# \{0,1\}//p' "$0" >&2; exit 2; }
lock=$(dirname -- "$(realpath -- "$0")")/tools.lock
read -r _ nixpkgs_revision nixpkgs_nar_hash < <(grep '^nixpkgs ' "$lock")
nixpkgs=github:NixOS/nixpkgs/$nixpkgs_revision
mapfile -t packages < <(awk '$1 != "nixpkgs" && NF == 2 {print $1}' "$lock")
mapfile -t paths < <(awk '$1 != "nixpkgs" && NF == 2 {print $2}' "$lock")

evaluate() {
	[[ $(nix flake metadata --json "$nixpkgs" | jq -r .locked.narHash) == "$nixpkgs_nar_hash" ]] || {
		echo 'image tool nixpkgs source differs from its pinned NAR hash' >&2
		exit 1
	}
	local package
	for package in "${packages[@]}"; do
		printf '%s %s\n' "$package" "$(nix eval --raw "$nixpkgs#$package.outPath")"
	done
}

if [[ $1 == --lock ]]; then
	{
		echo "# Generated by deploy/image/tools.sh --lock; edit the nixpkgs line, then regenerate."
		echo "nixpkgs $nixpkgs_revision $nixpkgs_nar_hash"
		evaluate
	} > "$lock.new"
	mv -f -- "$lock.new" "$lock"
	exit 0
fi

substituters=()
if [[ -n ${TS_IMAGE_TOOL_CACHE:-} ]]; then
	# Ahead of cache.nixos.org, so the whole closure comes from local disk.
	substituters=(--extra-substituters "$TS_IMAGE_TOOL_CACHE?trusted=1&priority=10")
fi
started=$SECONDS
if ! nix build --no-link "${substituters[@]}" "${paths[@]}"; then
	echo 'pinned image tools are not in a binary cache; building them from nixpkgs'
	diff -u <(awk '$1 != "nixpkgs" && NF == 2' "$lock") <(evaluate) || {
		echo 'tools.lock differs from the pinned nixpkgs outputs; run deploy/image/tools.sh --lock' >&2
		exit 1
	}
	installables=()
	for package in "${packages[@]}"; do installables+=("$nixpkgs#$package"); done
	nix build --no-link "${substituters[@]}" "${installables[@]}"
	if [[ -n ${TS_IMAGE_TOOL_CACHE:-} ]]; then
		nix copy --to "$TS_IMAGE_TOOL_CACHE?compression=zstd&parallel-compression=true" "${paths[@]}"
	fi
fi
echo "image tools ready nixpkgs=$nixpkgs_revision seconds=$((SECONDS - started))"
lock_sha256=$(sha256sum -- "$lock" | cut -d ' ' -f 1)
export TS_IMAGE_TOOLS_ID="nixpkgs=$nixpkgs_revision lock_sha256=$lock_sha256"
tool_path=
for path in "${paths[@]}"; do tool_path+="$path/bin:"; done
PATH="$tool_path$PATH" exec "$@"
